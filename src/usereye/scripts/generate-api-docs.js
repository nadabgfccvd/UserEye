#!/usr/bin/env node
'use strict';

/**
 * Public API reference generator (roadmap M10, Phase 6).
 *
 * `types/*.d.ts` already describes the whole public surface and is gated by
 * `check-api-surface.js`. This turns the same declarations — plus the JSDoc
 * that precedes them — into `docs/API.md`, so the reference can never describe
 * an export the package does not have.
 *
 * Usage: node scripts/generate-api-docs.js [--check]
 */

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const outPath = path.join(root, 'docs', 'API.md');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));

const SOURCES = ['types/index.d.ts', 'types/usereye-config.d.ts'];

/** Strip a JSDoc block down to its prose. */
function cleanDoc(block) {
  if (!block) return '';
  return block
    .replace(/^\s*\/\*\*/, '')
    .replace(/\*\/\s*$/, '')
    .split('\n')
    .map(line =>
      line
        .replace(/^\s*\*ic?\s?/, '')
        .replace(/^\s*\*\s?/, '')
        .trimEnd(),
    )
    .join('\n')
    .trim();
}

/**
 * Extract top-level declarations with their leading JSDoc.
 * A hand-rolled scanner is deliberate: pulling in a TS AST dependency for a
 * docs script would put a heavyweight devDependency on the release path.
 */
function extractDeclarations(source) {
  const declarations = [];
  const pattern =
    /(\/\*\*[\s\S]*?\*\/\s*)?export\s+(declare\s+)?(const|function|class|interface|type|enum)\s+([A-Za-z0-9_$]+)/g;
  let match;
  while ((match = pattern.exec(source))) {
    const [, doc, , kind, name] = match;
    const declarationStart = match.index + (doc ? doc.length : 0);
    declarations.push({
      kind,
      name,
      signature: readSignature(source, declarationStart, kind),
      doc: cleanDoc(doc),
    });
  }
  return declarations;
}

/**
 * Read a declaration's full signature: up to the terminating `;` for values and
 * type aliases, up to the opening `{` for classes/interfaces (their bodies are
 * documented member-by-member, not dumped wholesale).
 */
function readSignature(source, start, kind) {
  const stopAtBrace = kind === 'class' || kind === 'interface' || kind === 'enum';
  let depth = 0;
  for (let index = start; index < source.length; index += 1) {
    const character = source[index];
    if (character === '(' || character === '<' || character === '[') depth += 1;
    if (character === ')' || character === '>' || character === ']') depth -= 1;
    if (depth <= 0 && ((stopAtBrace && character === '{') || (!stopAtBrace && character === ';'))) {
      return source
        .slice(start, index)
        .replace(/^export\s+(declare\s+)?/, '')
        .replace(/\s+/g, ' ')
        .trim();
    }
  }
  return source
    .slice(start, start + 160)
    .replace(/\s+/g, ' ')
    .trim();
}

const KIND_LABEL = {
  class: 'Classes',
  function: 'Functions',
  const: 'Values',
  interface: 'Interfaces',
  type: 'Type aliases',
  enum: 'Enums',
};

function render() {
  const sections = [];
  for (const relative of SOURCES) {
    const filePath = path.join(root, relative);
    if (!fs.existsSync(filePath)) continue;
    const declarations = extractDeclarations(fs.readFileSync(filePath, 'utf8'));
    const grouped = new Map();
    for (const declaration of declarations) {
      const label = KIND_LABEL[declaration.kind] || 'Other';
      if (!grouped.has(label)) grouped.set(label, []);
      grouped.get(label).push(declaration);
    }
    const body = [];
    for (const label of ['Classes', 'Functions', 'Values', 'Interfaces', 'Type aliases', 'Enums', 'Other']) {
      const items = grouped.get(label);
      if (!items || !items.length) continue;
      body.push(`### ${label}`);
      body.push('');
      for (const item of items.sort((a, b) => a.name.localeCompare(b.name))) {
        body.push(`#### \`${item.name}\``);
        body.push('');
        body.push('```ts');
        body.push(item.signature);
        body.push('```');
        body.push('');
        if (item.doc) {
          body.push(item.doc);
          body.push('');
        }
      }
    }
    sections.push(`## \`${relative}\`\n\n${body.join('\n')}`);
  }

  return `<!-- GENERATED by scripts/generate-api-docs.js — do not edit by hand. -->

# UserEye ${pkg.version} — API reference

\`\`\`js
const { UserEye, loadConfig, AdaptiveExplorer } = require('usereye');
\`\`\`

Subpath entry points declared in \`exports\`:

${Object.keys(pkg.exports || {})
  .filter(key => key !== './package.json')
  .map(key => `- \`usereye${key.replace(/^\./, '')}\``)
  .join('\n')}

## The \`issue\` data model

Every finding in \`result.json\` — both the surfaced \`issues\` list and the
complete \`issuesAll\` list — carries the same shape. Automation built on top of
UserEye should read these fields and nothing else:

| Field | Meaning |
| --- | --- |
| \`fingerprint\` | Stable identity of the finding across runs. \`--compare\` diffs on this. |
| \`severity\` | \`blocker\` \\| \`critical\` \\| \`major\` \\| \`minor\`. Drives the gates. |
| \`confidence\` | \`high\` \\| \`medium\` \\| \`low\`. How sure the detector is. |
| \`kind\` | \`defect\` \\| \`risk\` \\| \`signal\` \\| \`opinion\`. Opinions are recognized accepted patterns. |
| \`triage\` / \`acceptedPattern\` | \`accepted-pattern\` lane and the stable recognized-pattern ID; never a CI failure. |
| \`source\` | Which subsystem produced it (\`axe\`, \`code-quality\`, \`explorer\`, …). |
| \`code\` | Machine-readable rule identifier within that source. |
| \`surfaced\` | Whether the finding passed \`findings.minConfidence\` into \`issues\`. |
| \`title\` / \`expected\` / \`actual\` / \`technical\` | Human-readable evidence. |

\`issues\` ⊆ \`issuesAll\`. Calming the report never destroys evidence: everything
observed stays in \`issuesAll\` with \`surfaced: false\`.

## Command audit

\`result.commandAudit\` lists every command that originated from the target
repository, whether it was \`executed\` or \`blocked\`, and why. \`shell\` is always
\`false\` — UserEye never invokes a shell.

${sections.join('\n\n')}
`;
}

/**
 * Format generated output with the repository's own Prettier config, so the
 * generator and `npm run format:check` can never disagree about the file they
 * both own. Prettier is a devDependency; if it is absent (consumer install)
 * the raw text is returned unchanged.
 *
 * @param {string} content
 * @param {string} filepath Used by Prettier to infer the parser.
 * @returns {Promise<string>}
 */
async function formatGenerated(content, filepath) {
  let prettier;
  try {
    prettier = require('prettier');
  } catch {
    return content;
  }
  const options = (await prettier.resolveConfig(filepath)) || {};
  return prettier.format(content, { ...options, filepath });
}

async function main() {
  const content = await formatGenerated(render(), outPath);
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  if (process.argv.includes('--check')) {
    const actual = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : null;
    if (actual !== content) {
      console.error('api-docs: FAIL — docs/API.md is out of date. Run npm run docs:api.');
      process.exit(1);
    }
    console.log('api-docs: OK — docs/API.md matches the declared type surface.');
    return;
  }
  fs.writeFileSync(outPath, content);
  console.log(`api-docs: wrote ${path.relative(root, outPath)}.`);
}

main().catch(error => {
  console.error(`api-docs: FAIL — ${error.message}`);
  process.exit(1);
});
